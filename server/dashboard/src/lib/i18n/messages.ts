export function translate(
  locale: Locale,
  message: string,
  values: Record<string, string | number> = {},
) {
  const text = locale === "zh-CN" ? (zhCN[message] ?? message) : message;
  return text.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  );
}
